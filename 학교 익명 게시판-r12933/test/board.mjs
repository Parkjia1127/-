function decryptPush(sent, client, auth) {
  const keyEnd = 21 + sent.body[20], salt = sent.body.subarray(0,16), pub = sent.body.subarray(21,keyEnd);
  const ikm = hkdfSync('sha256',client.computeSecret(pub),Buffer.from(auth,'base64url'),Buffer.concat([Buffer.from('WebPush: info\0'), client.getPublicKey(), pub]),32);
  const key = hkdfSync('sha256',ikm,salt,'Content-Encoding: aes128gcm\0',16);
  const nonce = hkdfSync('sha256',ikm,salt,'Content-Encoding: nonce\0',12);
  const decipher = createDecipheriv('aes-128-gcm',Buffer.from(key),Buffer.from(nonce));
  decipher.setAuthTag(sent.body.subarray(-16));
  return Buffer.concat([decipher.update(sent.body.subarray(keyEnd,-16)),decipher.final()]).toString();
}
